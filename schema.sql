-- ---------- PENANDA VERSI ----------
create or replace function kas_bump() returns trigger language plpgsql as $$
begin update kas_meta set version = version + 1 where id = 1; return null; end $$;

do $$ declare t text; begin
  foreach t in array array['kas_settings','kas_students','kas_payments','kas_tx','kas_ann'] loop
    execute format('drop trigger if exists %I on %I', t || '_bump', t);
    execute format('create trigger %I after insert or update or delete on %I for each statement execute function kas_bump()', t || '_bump', t);
  end loop;
end $$;

-- hapus transaksi otomatis ("Kas M1 Jan — Nama") => batalkan centang bayarnya juga
create or replace function kas_tx_del() returns trigger language plpgsql as $$
begin
  if old.key is not null and old.key like '%|%' then
    delete from kas_payments where student_id = split_part(old.key, '|', 1)::bigint and idx = split_part(old.key, '|', 2)::int;
  end if;
  return old;
end $$;
drop trigger if exists kas_tx_del_t on kas_tx;
create trigger kas_tx_del_t after delete on kas_tx for each row execute function kas_tx_del();

-- ---------- FUNGSI BANTU ----------
create or replace function kas_today() returns date language sql stable as
$$ select (now() at time zone 'Asia/Jakarta')::date $$;

create or replace function kas_idx_label(i int) returns text language sql immutable as
$$ select 'M' || (i % 4 + 1) || ' ' || (array['Jan','Feb','Mar','Apr','Mei','Jun','Jul','Agu','Sep','Okt','Nov','Des'])[i / 4 + 1] $$;

create or replace function kas_data() returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'settings', (select jsonb_build_object('kelas', kelas, 'tahun', tahun, 'mulaiBulan', mulai_bulan, 'nominal', nominal,
                  'bendahara', bendahara, 'wa', wa, 'spreadsheetUrl', spreadsheet_url, 'qris', qris) from kas_settings where id = 1),
    'students', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'no', no, 'nama', nama, 'hp', hp) order by no, id) from kas_students), '[]'::jsonb),
    'paid', coalesce((select jsonb_object_agg(s.id::text,
                coalesce((select jsonb_agg(p.idx order by p.idx) from kas_payments p where p.student_id = s.id), '[]'::jsonb))
              from kas_students s), '{}'::jsonb),
    'tx', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'tgl', to_char(tgl, 'YYYY-MM-DD'), 'tipe', tipe, 'ket', ket,
                  'jumlah', jumlah, 'siswaId', coalesce(siswa_id, 0), 'key', coalesce(key, '')) order by tgl desc, id desc) from kas_tx), '[]'::jsonb),
    'ann', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'tgl', to_char(tgl, 'YYYY-MM-DD'), 'judul', judul, 'isi', isi, 'pin', pin)
                  order by tgl desc, id desc) from kas_ann), '[]'::jsonb)
  )
$$;

-- cek PIN (dengan pembatas: 8x salah => terkunci 5 menit)
create or replace function kas_auth(p_pin text) returns boolean language plpgsql security definer set search_path = public as $$
declare s kas_secret%rowtype; ok boolean;
begin
  select * into s from kas_secret where id = 1;
  if s.locked_until is not null and s.locked_until > now() then return false; end if;
  ok := s.hash = encode(sha256(convert_to(s.salt || coalesce(p_pin, ''), 'UTF8')), 'hex');
  if ok then
    update kas_secret set fails = 0, locked_until = null where id = 1;
  elsif s.fails + 1 >= 8 then
    update kas_secret set fails = 0, locked_until = now() + interval '5 minutes' where id = 1;
  else
    update kas_secret set fails = s.fails + 1 where id = 1;
  end if;
  return ok;
end $$;

create or replace function kas_set_paid(p_sid bigint, p_idx int, p_paid boolean) returns void language plpgsql security definer set search_path = public as $$
declare s kas_students%rowtype; k text := p_sid || '|' || p_idx; nom int;
begin
  select * into s from kas_students where id = p_sid;
  if not found then raise exception 'Siswa tidak ditemukan'; end if;
  if p_idx < 0 or p_idx > 47 then raise exception 'Minggu tidak valid'; end if;
  if p_paid then
    insert into kas_payments (student_id, idx) values (p_sid, p_idx) on conflict do nothing;
    select nominal into nom from kas_settings where id = 1;
    insert into kas_tx (tgl, tipe, ket, jumlah, siswa_id, key)
    values (kas_today(), 'Masuk', 'Kas ' || kas_idx_label(p_idx) || ' — ' || s.nama, nom, p_sid, k)
    on conflict (key) do nothing;
  else
    delete from kas_tx where key = k;
    delete from kas_payments where student_id = p_sid and idx = p_idx;
  end if;
end $$;

create or replace function kas_renumber() returns void language sql security definer set search_path = public as $$
  update kas_students s set no = x.rn from (select id, row_number() over (order by no, id) as rn from kas_students) x where s.id = x.id and s.no <> x.rn
$$;

-- ---------- FUNGSI UNTUK WEB (dipanggil anon) ----------
create or replace function kas_get() returns jsonb language sql stable security definer set search_path = public as
$$ select jsonb_build_object('ok', true, 'data', kas_data()) $$;

create or replace function kas_login(p_pin text) returns jsonb language plpgsql security definer set search_path = public as $$
begin
  if kas_auth(p_pin) then return jsonb_build_object('ok', true); end if;
  return jsonb_build_object('ok', false, 'error', 'PIN salah (salah 8x = terkunci 5 menit)');
end $$;

create or replace function kas_do(p_pin text, p_action text, p jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare i int; sid bigint; aid bigint; st jsonb; v_salt text;
begin
  if not kas_auth(p_pin) then
    return jsonb_build_object('ok', false, 'error', 'Khusus admin. PIN salah/belum masuk.');
  end if;
  p := coalesce(p, '{}'::jsonb);

  case p_action
    when 'togglePaid' then
      perform kas_set_paid((p->>'studentId')::bigint, (p->>'idx')::int, coalesce((p->>'paid')::boolean, false));
    when 'payMany' then
      for i in select jsonb_array_elements_text(p->'idxs')::int loop
        perform kas_set_paid((p->>'studentId')::bigint, i, true);
      end loop;
    when 'addTx' then
      insert into kas_tx (tgl, tipe, ket, jumlah) values ((p->>'tgl')::date, p->>'tipe', coalesce(p->>'ket', ''), (p->>'jumlah')::bigint);
    when 'updateTx' then
      update kas_tx set tgl = (p->>'tgl')::date, tipe = p->>'tipe', ket = coalesce(p->>'ket', ''), jumlah = (p->>'jumlah')::bigint
      where id = (p->>'id')::bigint;
    when 'deleteTx' then
      delete from kas_tx where id = (p->>'id')::bigint;
    when 'saveAnn' then
      aid := coalesce(nullif(p->>'id', '')::bigint, 0);
      if aid > 0 then
        update kas_ann set judul = p->>'judul', isi = coalesce(p->>'isi', ''), pin = coalesce((p->>'pin')::boolean, false) where id = aid;
      else
        insert into kas_ann (tgl, judul, isi, pin) values (kas_today(), p->>'judul', coalesce(p->>'isi', ''), coalesce((p->>'pin')::boolean, false));
      end if;
    when 'deleteAnn' then
      delete from kas_ann where id = (p->>'id')::bigint;
    when 'saveSettings' then
      st := coalesce(p->'settings', '{}'::jsonb);
      update kas_settings set
        kelas           = coalesce(st->>'kelas', kelas),
        tahun           = coalesce(nullif(st->>'tahun', '')::int, tahun),
        mulai_bulan     = coalesce(nullif(st->>'mulaiBulan', '')::int, mulai_bulan),
        nominal         = coalesce(nullif(st->>'nominal', '')::int, nominal),
        bendahara       = coalesce(st->>'bendahara', bendahara),
        wa              = coalesce(st->>'wa', wa),
        spreadsheet_url = coalesce(st->>'spreadsheetUrl', spreadsheet_url)
      where id = 1;
    when 'saveQris' then
      update kas_settings set qris = coalesce(p->>'qris', '') where id = 1;
    when 'saveStudent' then
      update kas_students set nama = p->>'nama', hp = coalesce(p->>'hp', '') where id = (p->>'id')::bigint;
    when 'addStudent' then
      insert into kas_students (no, nama, hp) values ((select coalesce(max(no), 0) + 1 from kas_students), p->>'nama', coalesce(p->>'hp', ''));
    when 'deleteStudent' then
      sid := (p->>'id')::bigint;
      delete from kas_tx where siswa_id = sid;
      delete from kas_students where id = sid;
      perform kas_renumber();
    when 'changePin' then
      if length(coalesce(p->>'newPin', '')) < 4 then
        return jsonb_build_object('ok', false, 'error', 'PIN minimal 4 karakter');
      end if;
      v_salt := gen_random_uuid()::text;
      update kas_secret set salt = v_salt, hash = encode(sha256(convert_to(v_salt || (p->>'newPin'), 'UTF8')), 'hex'), fails = 0, locked_until = null where id = 1;
    else
      return jsonb_build_object('ok', false, 'error', 'Aksi tidak dikenal');
  end case;

  return jsonb_build_object('ok', true, 'data', kas_data());
exception when others then
  return jsonb_build_object('ok', false, 'error', sqlerrm);
end $$;

-- ---------- FUNGSI UNTUK SPREADSHEET (hanya service_role / kunci rahasia) ----------
create or replace function kas_sync_get() returns jsonb language sql stable security definer set search_path = public as
$$ select jsonb_build_object('version', (select version from kas_meta where id = 1), 'data', kas_data()) $$;

create or replace function kas_sync_version() returns bigint language sql stable security definer set search_path = public as
$$ select version from kas_meta where id = 1 $$;

-- centang dari spreadsheet: [{"studentId":1,"idx":0,"paid":true}, ...]
create or replace function kas_sync_paid(p_cells jsonb) returns void language plpgsql security definer set search_path = public as $$
declare c jsonb;
begin
  for c in select * from jsonb_array_elements(coalesce(p_cells, '[]'::jsonb)) loop
    begin
      perform kas_set_paid((c->>'studentId')::bigint, (c->>'idx')::int, coalesce((c->>'paid')::boolean, false));
    exception when others then null;  -- abaikan baris yang tidak valid
    end;
  end loop;
end $$;

-- isi sheet -> database.
--   p_auth = true : sheet dianggap paling baru; baris yang hilang di sheet ikut dihapus dan urutan mengikuti sheet.
--   p_auth = false: hanya tambah/ubah (aman kalau sheet belum sempat ikut perubahan terbaru dari web).
-- Baris yang masih punya ID tapi isinya sengaja/sementara kosong TIDAK dihapus (hapus baris = klik kanan > Hapus baris).
-- p_table: students | tx | ann | settings
create or replace function kas_sync_apply(p_table text, p_rows jsonb, p_auth boolean) returns void
language plpgsql security definer set search_path = public as $$
declare r jsonb; rid bigint; pos int := 0; ids bigint[] := '{}'; k text; found boolean;
begin
  p_rows := coalesce(p_rows, '[]'::jsonb);
  if p_table = 'students' then
    for r in select * from jsonb_array_elements(p_rows) loop
      pos := pos + 1;
      rid := nullif(r->>'id', '')::bigint;
      found := rid is not null and exists (select 1 from kas_students where id = rid);
      if found then ids := ids || rid; end if;
      continue when coalesce(trim(r->>'nama'), '') = '';
      if found then
        update kas_students set nama = r->>'nama', hp = coalesce(r->>'hp', ''), no = case when p_auth then pos else no end where id = rid;
      else
        insert into kas_students (no, nama, hp)
        values (case when p_auth then pos else (select coalesce(max(no), 0) + 1 from kas_students) end, r->>'nama', coalesce(r->>'hp', ''))
        returning id into rid;
        ids := ids || rid;
      end if;
    end loop;
    if p_auth then
      delete from kas_tx where siswa_id is not null and siswa_id <> all (ids);
      delete from kas_students where id <> all (ids);
    end if;
    perform kas_renumber();

  elsif p_table = 'tx' then
    for r in select * from jsonb_array_elements(p_rows) loop
      rid := nullif(r->>'id', '')::bigint;
      found := rid is not null and exists (select 1 from kas_tx where id = rid);
      if found then ids := ids || rid; end if;
      continue when coalesce(r->>'tipe', '') not in ('Masuk', 'Keluar') or coalesce(r->>'tgl', '') = '' or coalesce(r->>'jumlah', '') = '';
      if found then
        update kas_tx set tgl = (r->>'tgl')::date, tipe = r->>'tipe', ket = coalesce(r->>'ket', ''), jumlah = (r->>'jumlah')::bigint where id = rid;
      else
        insert into kas_tx (tgl, tipe, ket, jumlah) values ((r->>'tgl')::date, r->>'tipe', coalesce(r->>'ket', ''), (r->>'jumlah')::bigint) returning id into rid;
        ids := ids || rid;
      end if;
    end loop;
    if p_auth then delete from kas_tx where id <> all (ids); end if;

  elsif p_table = 'ann' then
    for r in select * from jsonb_array_elements(p_rows) loop
      rid := nullif(r->>'id', '')::bigint;
      found := rid is not null and exists (select 1 from kas_ann where id = rid);
      if found then ids := ids || rid; end if;
      continue when coalesce(trim(r->>'judul'), '') = '';
      if found then
        update kas_ann set tgl = coalesce(nullif(r->>'tgl', '')::date, tgl), judul = r->>'judul', isi = coalesce(r->>'isi', ''), pin = coalesce((r->>'pin')::boolean, false) where id = rid;
      else
        insert into kas_ann (tgl, judul, isi, pin) values (coalesce(nullif(r->>'tgl', '')::date, kas_today()), r->>'judul', coalesce(r->>'isi', ''), coalesce((r->>'pin')::boolean, false)) returning id into rid;
        ids := ids || rid;
      end if;
    end loop;
    if p_auth then delete from kas_ann where id <> all (ids); end if;

  elsif p_table = 'settings' then
    -- [{"k":"kelas","v":"8B"}, ...]
    for r in select * from jsonb_array_elements(p_rows) loop
      k := r->>'k';
      begin
        if k = 'kelas' then update kas_settings set kelas = coalesce(r->>'v', kelas);
        elsif k = 'tahun' then update kas_settings set tahun = coalesce(nullif(r->>'v', '')::int, tahun);
        elsif k = 'mulaiBulan' then update kas_settings set mulai_bulan = coalesce(nullif(r->>'v', '')::int, mulai_bulan);
        elsif k = 'nominal' then update kas_settings set nominal = coalesce(nullif(r->>'v', '')::int, nominal);
        elsif k = 'bendahara' then update kas_settings set bendahara = coalesce(r->>'v', bendahara);
        elsif k = 'wa' then update kas_settings set wa = coalesce(r->>'v', wa);
        elsif k = 'spreadsheetUrl' then update kas_settings set spreadsheet_url = coalesce(r->>'v', spreadsheet_url);
        elsif k = 'qris' then update kas_settings set qris = coalesce(r->>'v', qris);
        end if;
      exception when others then null;
      end;
    end loop;
  else
    raise exception 'Tabel tidak dikenal: %', p_table;
  end if;
end $$;

-- ---------- HAK AKSES FUNGSI ----------
do $$
declare f text; has_roles boolean := exists (select 1 from pg_roles where rolname = 'anon');
begin
  foreach f in array array[
    'kas_bump()', 'kas_tx_del()', 'kas_today()', 'kas_idx_label(int)', 'kas_data()', 'kas_auth(text)',
    'kas_set_paid(bigint,int,boolean)', 'kas_renumber()', 'kas_get()', 'kas_login(text)', 'kas_do(text,text,jsonb)',
    'kas_sync_get()', 'kas_sync_version()', 'kas_sync_paid(jsonb)', 'kas_sync_apply(text,jsonb,boolean)'
  ] loop
    execute format('revoke all on function %s from public', f);
    if has_roles then
      execute format('revoke all on function %s from anon, authenticated', f);
    end if;
  end loop;
  if has_roles then
    -- web (anon) hanya boleh 3 fungsi ini
    grant execute on function kas_get(), kas_login(text), kas_do(text,text,jsonb) to anon, authenticated;
    -- spreadsheet (kunci rahasia / service_role)
    grant execute on function kas_sync_get(), kas_sync_version(), kas_sync_paid(jsonb), kas_sync_apply(text,jsonb,boolean) to service_role;
    revoke all on all tables in schema public from anon, authenticated;
  end if;
end $$;

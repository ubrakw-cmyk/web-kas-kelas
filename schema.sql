-- ---------- TABEL ----------
create table if not exists kas_settings (
  id              int primary key default 1 check (id = 1),
  kelas           text not null default 'Kelas',
  tahun           int  not null default extract(year  from now())::int,
  mulai_bulan     int  not null default extract(month from now())::int,
  nominal         int  not null default 5000,
  bendahara       text not null default 'Kucay',
  wa              text not null default '',
  spreadsheet_url text not null default '',
  qris            text not null default ''
);
insert into kas_settings (id) values (1) on conflict do nothing;

create table if not exists kas_students (
  id   bigint generated by default as identity primary key,
  no   int  not null default 0,
  nama text not null,
  hp   text not null default ''
);

create table if not exists kas_payments (
  student_id bigint not null references kas_students(id) on delete cascade,
  idx        int    not null check (idx between 0 and 47),
  primary key (student_id, idx)
);

create table if not exists kas_tx (
  id       bigint generated by default as identity primary key,
  tgl      date   not null default current_date,
  tipe     text   not null check (tipe in ('Masuk', 'Keluar')),
  ket      text   not null default '',
  jumlah   bigint not null check (jumlah >= 0),
  siswa_id bigint,
  key      text unique
);

create table if not exists kas_ann (
  id    bigint generated by default as identity primary key,
  tgl   date    not null default current_date,
  judul text    not null,
  isi   text    not null default '',
  pin   boolean not null default false
);

create table if not exists kas_secret (
  id           int primary key default 1 check (id = 1),
  salt         text not null,
  hash         text not null,
  fails        int  not null default 0,
  locked_until timestamptz
);

-- penanda "ada perubahan" untuk sinkron ke spreadsheet
create table if not exists kas_meta (id int primary key default 1 check (id = 1), version bigint not null default 0);
insert into kas_meta (id) values (1) on conflict do nothing;

-- PIN admin awal (disimpan sebagai hash, bukan teks biasa)
-- >>> GANTI 'PIN_ADMIN_AWAL' dengan PIN yang kamu mau <<<
insert into kas_secret (id, salt, hash)
select 1, s, encode(sha256(convert_to(s || 'PIN_ADMIN_AWAL', 'UTF8')), 'hex')
from (select gen_random_uuid()::text as s) x
on conflict (id) do nothing;

